function DeckCard({ deck }: { deck: ShowcaseDeck }) {
  return (
    <article className="sc-deck" aria-label={`${deck.title} deck`}>
      <div className="sc-deck-head">
        <p className="sc-badges">
          <span className={`badge sc-label-${deck.label}`}>{deck.label}</span>
          <span className="badge">
            {deck.system} · {deck.systemStatus}
          </span>
          <span className="badge">seed {deck.seed}</span>
          <span className="badge">validator OK</span>
        </p>
        <h3 className="sc-deck-title">{deck.title}</h3>
        <p className="sc-source">
          {deck.sourceUrl ? <a href={deck.sourceUrl}>{deck.source}</a> : deck.source}
          {' @ '}
          <code>{deck.sha.startsWith('n/a') ? deck.sha : deck.sha.slice(0, 7)}</code>
          {' · '}
          {deck.branch} · purpose “{deck.purpose}”
        </p>
        <p className="sc-stats">
          <span>{deck.files}</span>
          <span>
            claims {deck.claims.total} ({deck.claims.verified}v/{deck.claims.suggestion}s/
            {deck.claims.ungrounded}u)
          </span>
          <span>
            {deck.slides} slides · {deck.boxes} text boxes · {deck.editableChars.toLocaleString()} editable
            chars
          </span>
        </p>
        <p className="sc-note">{deck.note}</p>
      </div>
      <div className="sc-strip">
        <img src={deck.filmstrip} alt={deck.filmstripAlt} loading="lazy" />
        <p className="sc-strip-cap">
          all {deck.slides} slides · geometry preview (see method note)
        </p>
      </div>
      <div className="sc-files">
        <a className="btn-secondary" href={deck.pptx} download>
          Download .pptx ({(deck.pptxBytes / 1024).toFixed(0)} KB)
        </a>
        <a href={deck.deckJson}>deck JSON</a>
        <a href={deck.provenanceJson}>provenance JSON</a>
        {deck.extraFiles.map((f) => (
          <a key={f.href} href={f.href}>
            {f.label}
          </a>
        ))}
      </div>
      <details className="sc-repro">
        <summary>Reproduce this deck</summary>
        <pre>
          <code>{deck.repro}</code>
        </pre>
      </details>
    </article>
  );
}

